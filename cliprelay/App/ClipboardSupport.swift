struct HistoryItemLabel: View {
    let row: Summary
    let library: Library?
    @State private var attachment: ClipAttachment?

    private var isAttachment: Bool { row.kind == "Image" || row.kind == "File" }
    private var details: String {
        ([row.source, ClipRelayPreferences.localized(row.kind)] + [attachment?.formattedSize].compactMap { $0 })
            .joined(separator: " · ")
    }

    var body: some View {
        HStack(spacing: 10) {
            if isAttachment {
                Group {
                    if let image = attachment?.thumbnail {
                        Image(decorative: image, scale: 1)
                            .resizable()
                            .scaledToFit()
                    } else {
                        Image(systemName: attachment?.symbol ?? (row.kind == "Image" ? "photo" : "doc"))
                            .font(.system(size: 20))
                            .foregroundStyle(.secondary)
                    }
                }
                .frame(width: 44, height: 36)
                .background(.quaternary, in: RoundedRectangle(cornerRadius: 5))
                .clipShape(RoundedRectangle(cornerRadius: 5))
                .accessibilityHidden(true)
            }
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 4) {
                    if row.pinned {
                        Image(systemName: "pin.fill")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                            .accessibilityLabel(Text("Pinned"))
                    }
                    Text(row.name).lineLimit(2)
                }
                Text(details).font(.caption).foregroundStyle(.secondary)
            }
        }
        .task(id: row.id) {
            guard isAttachment, let library else { return }
            let loaded = await ClipAttachment.load(row.id, from: library)
            guard !Task.isCancelled else { return }
            attachment = loaded
        }
    }
}

func materialize(_ clip: Clip, directoryID: UUID? = nil) throws -> URL {
    let dir = FileManager.default.temporaryDirectory
        .appendingPathComponent("cc.macseek.cliprelay", isDirectory: true)
        .appendingPathComponent((directoryID ?? clip.id).uuidString, isDirectory: true)
    try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                            attributes: [.posixPermissions: 0o700])
    var name = clip.kind == "File" ? URL(fileURLWithPath: clip.name).lastPathComponent : "ClipRelay"
    guard !["", ".", "..", "/"].contains(name), !name.utf8.contains(0) else { throw RelayFailure.invalid }
    if (name as NSString).pathExtension.isEmpty, let ext = UTType(clip.type)?.preferredFilenameExtension {
        name += "." + ext
    }
    let url = dir.appendingPathComponent(name)
    try clip.bytes.write(to: url, options: .atomic)
    return url
}
