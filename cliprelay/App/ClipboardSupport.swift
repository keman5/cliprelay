struct MacClipBatch {
    var clips: [Clip] = []
    var failures: [String] = []

    mutating func read(_ name: String, _ load: () throws -> Clip) {
        do {
            let clip = try load()
            try clip.validate()
            clips.append(clip)
        } catch {
            failures.append("\(name) — \(ClipRelayPreferences.localized(error.localizedDescription))")
        }
    }

    func save(_ write: (Clip) throws -> Void) -> MacClipBatch {
        var saved = MacClipBatch(failures: failures)
        for (index, clip) in clips.enumerated() {
            saved.read(clipboardItemName(clip, index: index)) {
                try write(clip)
                return clip
            }
        }
        return saved
    }

    func report(_ heading: String) -> String {
        guard !failures.isEmpty else { return "" }
        return ([String(format: ClipRelayPreferences.localized(heading), clips.count)] + failures).joined(separator: "\n")
    }
}

private func clipboardItemName(_ clip: Clip, index: Int) -> String {
    clip.isFile == true ? clip.name : unnamedClipboardItem(index)
}

private func unnamedClipboardItem(_ index: Int) -> String {
    String(format: ClipRelayPreferences.localized("Item %lld"), index + 1)
}

@MainActor func isPrivateClipboard(_ pasteboard: NSPasteboard) -> Bool {
    containsPrivateClipboardItems(pasteboard.pasteboardItems ?? [])
}

@MainActor private func containsPrivateClipboardItems(_ items: [NSPasteboardItem]) -> Bool {
    let excluded: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]
    return items.contains { !excluded.isDisjoint(with: $0.types) }
}

@MainActor func clipboardClips(in pasteboard: NSPasteboard) throws -> MacClipBatch {
    guard let items = pasteboard.pasteboardItems, !items.isEmpty else { throw RelayFailure.invalid }
    guard !containsPrivateClipboardItems(items) else { throw RelayFailure.unauthorized }

    var batch = MacClipBatch()
    for (index, item) in items.enumerated() {
        let url = item.string(forType: .fileURL).flatMap(URL.init(string:))
        let name = url?.lastPathComponent
        batch.read(name.flatMap { $0.isEmpty ? nil : $0 } ?? unnamedClipboardItem(index)) {
            try clipboardClip(from: item)
        }
    }
    return batch
}

@MainActor private func clipboardClip(from item: NSPasteboardItem) throws -> Clip {
    if let value = item.string(forType: .fileURL), let url = URL(string: value), url.isFileURL {
        return try fileClip(url)
    }
    let images = item.types.filter { UTType($0.rawValue)?.conforms(to: .image) == true }
    var imageTooLarge = false
    for type in [.png] + images.filter({ $0 != .png }) {
        if let data = item.data(forType: type), !data.isEmpty {
            if data.count <= Clip.limit {
                return Clip(name: type.rawValue, type: type.rawValue, bytes: data)
            }
            imageTooLarge = true
        }
    }
    if imageTooLarge { throw RelayFailure.tooLarge }
    if !images.isEmpty { throw RelayFailure.invalid }
    let text = item.string(forType: .string)
    for type in [NSPasteboard.PasteboardType.rtf, .html] {
        if let data = item.data(forType: type) {
            return Clip(name: Clip.preview(text ?? type.rawValue), type: type.rawValue, bytes: data, plain: text)
        }
    }
    guard let text, !text.isEmpty else { throw RelayFailure.invalid }
    return .text(text)
}
