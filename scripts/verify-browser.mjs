import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/kevin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = process.argv[2] || 'http://localhost:8787';
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', args: ['--no-first-run'] });
const username = 'verify_ui_' + randomBytes(5).toString('hex');
const password = randomBytes(9).toString('hex');
console.log('Test user (cleanup via D1): ' + username);
const errors = [];
try {
  const context = await browser.newContext();
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('heading', { name: '欢迎使用 ClipNote 云端剪切板' }).waitFor();
  assert.equal(await page.getByText(/demo|演示账号|已注册账号状态/i).count(), 0);
  await page.getByRole('button', { name: '登录 / 注册新账号', exact: true }).click();
  await page.getByRole('button', { name: '免邮箱注册账号', exact: true }).click();
  await page.locator('#auth-username-input').fill(username);
  await page.locator('#auth-password-input').fill(password);
  await page.getByRole('button', { name: '完成注册并登录', exact: true }).click();
  await page.locator('#clipboard-composer-textarea').waitFor();
  await page.locator('#clipboard-composer-textarea').fill('后台 Edge 验证：真实账号持久化');
  await page.locator('#clipboard-composer-textarea').press('Enter');
  await page.getByText('后台 Edge 验证：真实账号持久化', { exact: true }).waitFor();
  await page.reload();
  await page.getByText('后台 Edge 验证：真实账号持久化', { exact: true }).waitFor();
  await page.getByRole('button', { name: /切换账号/ }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.getByRole('heading', { name: '欢迎使用 ClipNote 云端剪切板' }).waitFor();
  await page.getByRole('button', { name: '登录已有账号', exact: true }).click();
  await page.locator('#auth-username-input').fill(username);
  await page.locator('#auth-password-input').fill(password);
  await page.getByRole('button', { name: '立即登录', exact: true }).click();
  await page.getByText('后台 Edge 验证：真实账号持久化', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await context.close();
  console.log('PASS: background Microsoft Edge registration, save, reload, logout/login, mobile width, no JS errors');
  console.log('Test user (cleanup via D1): ' + username);
} finally { await browser.close(); }
